export type ChainSegment = 'up' | 'mid' | 'down'
export const SEGMENT_LABEL: Record<ChainSegment, string> = { up: '上游', mid: '中游', down: '下游' }

export interface Track {
  key: string
  name: string
  codes: string[] // 映射的国标行业代码（含名称，展示用）
  keywords: string[] // 经营范围关键词
}
export interface ChainNode {
  segment: ChainSegment
  tracks: Track[]
}
export interface Industry {
  id: string
  name: string
  desc: string
  chain: ChainNode[]
}

