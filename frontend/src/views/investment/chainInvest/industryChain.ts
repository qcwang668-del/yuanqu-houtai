// 工具：按赛道 key 聚合 codes / keywords（用于注入默认条件）
export function aggregateTracks(industryId: string, trackKeys: string[]) {
  const ind = INDUSTRIES.find((i) => i.id === industryId)
  const codes: string[] = []
  const keywords: string[] = []
  const names: string[] = []
  if (ind) {
    for (const node of ind.chain) {
      for (const tk of node.tracks) {
        if (trackKeys.includes(tk.key)) {
          names.push(tk.name)
          tk.codes.forEach((c) => codes.includes(c) || codes.push(c))
          tk.keywords.forEach((k) => keywords.includes(k) || keywords.push(k))
        }
      }
    }
  }
  return { industryName: ind?.name || '', trackNames: names, codes, keywords }
}
